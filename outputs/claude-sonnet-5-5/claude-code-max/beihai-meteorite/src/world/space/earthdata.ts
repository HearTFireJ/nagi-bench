export const LAND_POLYS: Poly[] = [EURASIA, AFRICA, AUSTRALIA, NORTH_AMERICA, SOUTH_AMERICA, ...ISLANDS];

function inPoly(poly: Poly, x: number, y: number): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const GW = 360;
const GH = 180;
let grid: Uint8Array | null = null;

/** 1° 分辨率的陆地位图（懒生成） */
function landGrid(): Uint8Array {
  if (grid) return grid;
  grid = new Uint8Array(GW * GH);
  for (let gy = 0; gy < GH; gy++) {
    const lat = 89.5 - gy;
    for (let gx = 0; gx < GW; gx++) {
      const lon = gx - 179.5;
      let land = 0;
      if (lat < -70 || lat > 82) land = 2; // 冰
      else {
        for (const p of LAND_POLYS) {
          if (inPoly(p, lon, lat)) {
            land = 1;
            break;
          }
        }
      }
      grid[gy * GW + gx] = land;
    }
  }
  return grid;
}

/** 0 = 海, 1 = 陆, 2 = 冰盖 */
export function landAt(lon: number, lat: number): number {
  const g = landGrid();
  let x = Math.floor(lon + 180);
  x = ((x % GW) + GW) % GW;
  let y = Math.floor(89.999 - lat);
  y = y < 0 ? 0 : y >= GH ? GH - 1 : y;
  return g[y * GW + x];
}
